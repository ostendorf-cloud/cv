package cv

import (
	"strings"
	"testing"
)

// sourceCanary is the first line of every generated source, cv.typ in
// typst's working directory. A payload that reached typst as code could read
// that file with #read("cv.typ"); the canary in the text layer would show it.
const sourceCanary = "Generated by cv render pdf"

// noSpace drops every whitespace character.
func noSpace(s string) string {
	return strings.Join(strings.Fields(s), "")
}

// TestPDFPrintsPayloadsLiterally compiles data full of typst syntax with the
// real typst and reads the text layer back: every payload prints as the text
// it is, and nothing is read from typst's working directory. The payloads sit
// in every free text the PDF prints: a position's title, employer and summary,
// the email, and a profile's platform and URL.
func TestPDFPrintsPayloadsLiterally(t *testing.T) {
	t.Parallel()

	cases := []struct {
		name    string
		payload string
		// printed is the payload as the text layer holds it: the payload
		// itself, unless a control character has no printed form.
		printed string
	}{
		{name: "read call", payload: `#read("cv.typ")`},
		{name: "read of an absolute path", payload: `#read("/etc/passwd")`},
		{name: "quote breaker", payload: `"); #read("cv.typ"); ("`},
		{name: "backslash quote breaker", payload: `\"); #read("cv.typ") //`},
		{name: "raw block", payload: "```typ #read(\"cv.typ\")``` and `x`"},
		{name: "markup characters", payload: `*bold* _em_ $x^2$ @ref <lbl> = Heading`},
		{name: "import", payload: `#import "cv.typ": *`},
		{name: "nul byte", payload: "before\x00after", printed: "beforeafter"},
		// The override reverses what follows it, as it does in any text:
		// pdftotext reads "right" as "thgir", wrapped in bidi marks.
		{name: "right to left override", payload: "left\u202eright", printed: "left"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			doc := Document{
				Experience: []ExperienceEntry{{
					ID: "e", Start: "2020-01",
					Title:    "Title " + tc.payload,
					Employer: "Employer " + tc.payload,
					Summary:  "Summary " + tc.payload,
				}},
				Contact: Contact{
					Email: "mail" + tc.payload + "@example.com",
					Profiles: []Profile{{
						Platform: "Platform " + tc.payload,
						URL:      "https://example.com/" + tc.payload,
					}},
				},
			}
			text := pdfText(t, compileReal(t, doc, "en"))

			if strings.Contains(text, sourceCanary) {
				t.Fatalf("the text layer holds the generated source, a payload ran as code:\n%s", text)
			}
			printed := tc.printed
			if printed == "" {
				printed = tc.payload
			}
			// The narrow sidebar wraps the email wherever it likes, so the
			// comparison ignores whitespace.
			bare := noSpace(text)
			for _, want := range []string{
				"Title " + printed,
				"Employer " + printed,
				"Summary " + printed,
				"mail" + printed,
				"Platform " + printed,
			} {
				if !strings.Contains(bare, noSpace(want)) {
					t.Errorf("text layer lacks %q:\n%s", want, text)
				}
			}
		})
	}
}
